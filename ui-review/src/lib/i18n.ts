const dictionaries: Record<LanguageCode, Record<TranslationKey, string>> = {
  "zh-CN": zhCN,
  "en-US": enUS,
};

export function isLanguageCode(value: string | null | undefined): value is LanguageCode {
  return value === "zh-CN" || value === "en-US";
}

export function translate(language: LanguageCode, key: TranslationKey, values?: TranslationValues): string {
  const template = dictionaries[language]?.[key] ?? dictionaries[DEFAULT_LANGUAGE][key] ?? key;
  if (!values) return template;

  return template.replace(/\{(\w+)\}/g, (match, token: string) => {
    const value = values[token];
    return value === undefined ? match : String(value);
  });
}
